const ref = (name: string, label: string, reference: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'reference',
  reference,
  ...extra,
});
const str = (name: string, label: string, maxLength = 255, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'string',
  maxLength,
  ...extra,
});
const bool = (
  name: string,
  label: string,
  defaultValue: boolean,
  extra: Partial<ColumnDef> = {},
): ColumnDef => ({
  name,
  label,
  type: 'boolean',
  defaultValue: defaultValue ? 'true' : 'false',
  ...extra,
});
const int = (name: string, label: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'integer',
  ...extra,
});
const price = (name: string, label: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'price',
  defaultValue: '0',
  ...extra,
});
const choice = (
  name: string,
  label: string,
  choices: ColumnDef['choices'],
  extra: Partial<ColumnDef> = {},
): ColumnDef => ({
  name,
  label,
  type: 'string',
  maxLength: 40,
  choices,
  choiceMode: 'dropdown_without_none',
  ...extra,
});

/** Many-to-many link table between a catalog record and another record. */
const link = (
  name: string,
  label: string,
  left: [string, string, string],
  right: [string, string, string],
): TableDef => ({
  name,
  label,
  plural: label,
  displayField: right[0],
  columns: [
    ref(left[0], left[1], left[2], { mandatory: true, cascade: 'delete' }),
    ref(right[0], right[1], right[2], { mandatory: true, cascade: 'delete' }),
  ],
  indexes: [[left[0], right[0]]],
});

