export const LANGUAGES: { code: Lang; name: string; dir: 'ltr' | 'rtl' }[] = [
  { code: 'en', name: 'English', dir: 'ltr' },
  { code: 'ar', name: 'العربية', dir: 'rtl' },
];

const STRINGS: Record<Lang, Record<string, string>> = { en: EN, ar: AR };

/** Right-to-left scripts (the portal mirrors its layout for these). */
const RTL = new Set(['ar', 'he', 'fa', 'ur']);

/** Normalizes a language tag (`ar-SA` -> `ar`); unsupported languages become English. */
export function normalizeLang(v: unknown): Lang {
  const base = String(v ?? '')
    .trim()
    .toLowerCase()
    .split(/[-_]/)[0];
  return base === 'ar' ? 'ar' : 'en';
}

export function isRtl(lang: string): boolean {
  return RTL.has(lang);
}

/** Translates a key, falling back to English and then to the key itself. */
export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const text = STRINGS[lang]?.[key] ?? EN[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Bundle for `GET /api/app/portal/i18n/:lang`. */
export function bundle(requested: string) {
  const lang = normalizeLang(requested);
  const strings = { ...EN, ...STRINGS[lang] };
  return {
    lang,
    requested: String(requested ?? ''),
    supported: LANGUAGES.map((l) => l.code),
    fallback: 'en',
    name: LANGUAGES.find((l) => l.code === lang)?.name ?? 'English',
    dir: isRtl(lang) ? 'rtl' : 'ltr',
    rtl: isRtl(lang),
    languages: LANGUAGES,
    strings,
  };
}
