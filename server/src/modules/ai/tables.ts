/** Tables of the AI module: ML solutions, prediction results, skill configuration, logs, virtual agent. */
import type { ChoiceDef, ColumnDef, TableDef } from '../../engine/types.js';

const c = (value: string, label: string, sequence: number): ChoiceDef => ({ value, label, sequence });
const str = (name: string, label: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'string',
  maxLength: 255,
  ...extra,
});
const int = (name: string, label: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'integer',
  ...extra,
});
const dec = (name: string, label: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'decimal',
  ...extra,
});
const bool = (
  name: string,
  label: string,
  defaultValue: boolean,
  extra: Partial<ColumnDef> = {},
): ColumnDef => ({
  name,
  label,
  type: 'boolean',
  defaultValue: defaultValue ? 'true' : 'false',
  ...extra,
});
const ref = (name: string, label: string, reference: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'reference',
  reference,
  ...extra,
});
const json = (name: string, label: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'json',
  ...extra,
});
const dt = (name: string, label: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({
  name,
  label,
  type: 'glide_date_time',
  ...extra,
});

