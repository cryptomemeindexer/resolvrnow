/** Test double implementing the provider interface; never calls a real LLM. */
class FakeProvider implements LlmProvider {
  readonly id = 'fake';
  readonly model = 'fake-model-1';
  calls: LlmRequest[] = [];
  next: Partial<LlmResult> | Error | null = null;
  reply = 'Issue\nGenerated by the fake model.';

  available(): boolean {
    return true;
  }

  async generate(req: LlmRequest): Promise<LlmResult> {
    this.calls.push(req);
    const n = this.next;
    this.next = null;
    if (n instanceof Error) throw n;
    return {
      text: this.reply,
      stop: 'end',
      model: this.model,
      usage: { input: 120, output: 30, cached: 0 },
      ...(n ?? {}),
    };
  }
}

let p: Platform;
let sys: Context;
let engine: AiEngine;
let agent: Context;
let caller: Context;
let callerId: string;
let reportUserId: string;

const run = (ctx: Context, skill: string, input: Record<string, unknown>) =>
  engine.skills.run(ctx, skill, input);

async function expectSkillError(
  promise: Promise<unknown>,
  status: number,
  code: string,
): Promise<SkillError> {
  try {
    await promise;
  } catch (e) {
    expect(e).toBeInstanceOf(SkillError);
    expect((e as SkillError).status).toBe(status);
    expect((e as SkillError).code).toBe(code);
    return e as SkillError;
  }
  throw new Error('expected a SkillError');
}

function incident(
  values: Record<string, unknown>,
  notes: { work_notes?: string; comments?: string }[] = [],
): Rec {
  const rec = sys.insert('incident', { caller_id: callerId, ...values });
  for (const n of notes) sys.update(rec, n);
  return sys.get('incident', rec.sysId)!;
}

